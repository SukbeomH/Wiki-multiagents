def economic_analysis_interface():
    """경제 분석 인터페이스"""
    st.subheader("💬 경제 분석")
    
    st.markdown("""
    ### AI 멀티 에이전트 분석 시스템
    
    AI 한국은행 경제 분석팀은 **Researcher**와 **Analyst** 두 개의 전문 에이전트가 협력하여 분석을 수행합니다.
    """)
    
    col1, col2 = st.columns(2)
    
    with col1:
        st.markdown("""
        #### 🔍 Researcher (정보 수집 전문가)
        
        **주요 역할:**
        - 업로드된 문서에서 관련 정보 검색
        - 웹에서 최신 경제 뉴스 수집
        - 출처 정보와 신뢰도 평가
        
        **수집 정보:**
        - 한국은행 공식 데이터
        - 경제 통계 및 지표
        - 정책 발표 및 보고서
        - 시장 반응 및 전문가 의견
        """)
    
    with col2:
        st.markdown("""
        #### ✍️ Analyst (경제 분석 전문가)
        
        **주요 역할:**
        - 수집된 정보를 종합 분석
        - 경제적 인사이트 도출
        - 명확한 결론 및 시사점 제시
        
        **분석 내용:**
        - 경제 트렌드 및 패턴 분석
        - 원인과 결과 관계 분석
        - 잠재적 영향 및 전망
        - 정책적 시사점 도출
        """)
    
    st.subheader("📊 분석 결과")
    
    st.markdown("""
    ### 분석 결과 구성
    
    **1. 분석 결과**
    - 심층적이고 통찰력 있는 분석 내용
    - 데이터 기반의 객관적 분석
    
    **2. 근거 및 출처**
    - 분석에 사용된 주요 근거들
    - 출처 정보 포함 (파일명, 페이지, URL)
    
    **3. 결론**
    - 명확하고 실행 가능한 결론
    - 신뢰도와 한계점 명시
    """)


def features_interface():
    """기능 설명 인터페이스"""
    st.subheader("📚 주요 기능")
    
    st.markdown("""
    ### 🔍 RAG (Retrieval-Augmented Generation)
    
    **기능 설명:**
    - 업로드된 문서에서 관련 정보를 검색하여 분석에 활용
    - 정확한 출처 정보와 함께 신뢰할 수 있는 분석 제공
    
    **검색 전략:**
    - MMR (Maximal Marginal Relevance): 다양성과 관련성 균형
    - Similarity: 유사도 기반 검색
    
    **설정 가능한 파라미터:**
    - 검색 결과 수 (K)
    - 가져올 결과 수 (Fetch K)
    - MMR 람다 값
    - 점수 임계값
    """)
    
    st.subheader("🌐 웹 검색")
    
    st.markdown("""
    ### 웹 검색 기능
    
    **기능 설명:**
    - 최신 경제 뉴스 및 시장 정보 수집
    - 실시간 데이터로 분석의 최신성 보장
    
    **검색 범위:**
    - 경제 뉴스 사이트
    - 금융 전문 매체
    - 정부 기관 발표
    - 전문가 의견 및 분석
    
    **활성화 방법:**
    - 사이드바에서 "🌐 웹검색" 토글 활성화
    - 기본적으로 활성화되어 있음
    """)
    
    st.subheader("📄 문서 관리")
    
    st.markdown("""
    ### 문서 업로드 및 관리
    
    **지원 형식:**
    - PDF 파일 (.pdf)
    - 한국은행 공식 문서
    - 경제 보고서 및 정책 자료
    
    **업로드 방법:**
    1. 사이드바의 파일 업로더 사용
    2. 드래그 앤 드롭 또는 파일 선택
    3. 업로드 완료 후 자동 인덱싱
    
    **문서 처리:**
    - 자동 텍스트 추출
    - 페이지별 분할
    - 임베딩 생성 및 저장
    - 빠른 검색을 위한 인덱스 구축
    """)


